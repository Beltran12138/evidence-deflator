/* Worked examples for a draft mandate, in the browser. A port of src/mandate_examples.py and of the rule
   check in src/agent_gate.py (check); tests/test_gate_features.py runs both on the same scopes and compares.
   The owner confirms these decisions before signing. Generated by code from the scope, not by a model. */
(function (root) {
  var OFF_LIST = ['TSLA', 'NVDA', 'DOGE', 'BTC', 'AAPL', 'QQQ', 'ZZZZ'];
  function r2(x) { return Math.round(x * 100) / 100; }
  function money(x) { return '$' + Math.round(x).toLocaleString('en-US'); }

  function check(order, ctx, cfg) {
    var reasons = [], sym = order.symbol, side = order.side, qty = order.qty, price = ctx.price;
    var notional = qty * price, pos = ctx.position;
    var reducing = (side === 'sell' && qty > 0 && qty <= pos) || (side === 'buy' && qty > 0 && qty <= -pos);
    if (cfg.allow && cfg.allow.length && cfg.allow.indexOf(sym) < 0) reasons.push(sym + ' 不在名单上');
    if (cfg.sides && cfg.sides.length && cfg.sides.indexOf(side) < 0 && !reducing) reasons.push('不允许' + (side === 'buy' ? '买入' : '卖出') + '开仓');
    if (cfg.max_position_usd != null && !reducing) {
      var after = pos + (side === 'buy' ? qty : -qty);
      var grows = Math.abs(after) > Math.abs(pos) || after * pos < 0;
      if (Math.abs(after) * price > cfg.max_position_usd && grows) reasons.push('仓位会到 ' + money(Math.abs(after) * price) + '，超过单标的上限 ' + money(cfg.max_position_usd));
    }
    if (cfg.max_order_usd != null && notional > cfg.max_order_usd) reasons.push('单笔 ' + money(notional) + '，超过上限 ' + money(cfg.max_order_usd));
    if (!reducing) {
      if (cfg.max_daily_loss_usd != null && ctx.loss_today >= cfg.max_daily_loss_usd) reasons.push('今天已亏到上限，只放行减仓');
      if (cfg.max_orders_per_day != null && ctx.orders_today >= cfg.max_orders_per_day) reasons.push('今天笔数已满');
    }
    return reasons;
  }

  function examples(scope) {
    var allow = (scope.allow || []).map(function (s) { return String(s).toUpperCase(); });
    var sides = scope.sides && scope.sides.length ? scope.sides : ['buy', 'sell'];
    var mo = scope.max_order_usd, mp = scope.max_position_usd, ml = scope.max_daily_loss_usd, mn = scope.max_orders_per_day;
    var sym = allow.length ? allow[0] : 'AAPL';
    var small = r2(mo != null ? Math.min(mo * 0.6, 300) : 300);
    var open = sides.indexOf('buy') >= 0 ? 'buy' : 'sell';
    var cases = [];
    function add(zh, symbol, side, usd, pos, loss, n) {
      cases.push({ title_zh: zh, order: { symbol: symbol, side: side, usd: r2(usd) },
                   situation: { position_usd: r2(pos || 0), loss_today: r2(loss || 0), orders_today: n || 0 } });
    }
    add('平常的一笔：' + (open === 'buy' ? '买' : '卖') + ' ' + sym + ' ' + money(small), sym, open, small);
    if (mo != null) add('比单笔上限多 1 美元：' + sym + ' ' + money(mo + 1), sym, open, mo + 1);
    if (allow.length) {
      var off = OFF_LIST.filter(function (s) { return allow.indexOf(s) < 0; })[0];
      add('不在名单上的标的：' + off + ' ' + money(small), off, open, small);
    }
    if (sides.indexOf('sell') < 0) add('手里没有 ' + sym + ' 时卖出（做空）', sym, 'sell', small);
    if (mp != null) {
      var held = Math.max(mp - (mo != null ? mo : mp) / 2, 0), buy = (mo != null ? mo : mp) * 0.9;
      add('已持有 ' + sym + ' ' + money(held) + '，再买 ' + money(buy) + '（超过单标的仓位上限 ' + money(mp) + '）',
          sym, open, buy, open === 'buy' ? held : -held);
    }
    if (ml != null) {
      add('今天已亏 ' + money(ml) + '，再开新仓 ' + money(small), sym, open, small, 0, ml);
      var h = Math.min(mp != null ? mp : 1000, 1000), cut = r2(h / 2);
      add('今天已亏 ' + money(ml) + '，卖出一半持仓止损 ' + money(cut), sym, open === 'buy' ? 'sell' : 'buy', cut,
          open === 'buy' ? h : -h, ml);
    }
    if (mn != null) add('今天已下满 ' + mn + ' 笔，再下一笔', sym, open, small, 0, 0, mn);
    var rules = { allow: allow, sides: scope.sides, max_order_usd: mo, max_position_usd: mp,
                  max_daily_loss_usd: ml, max_orders_per_day: mn };
    cases.forEach(function (c) {
      var p = 100, o = c.order, s = c.situation;
      var ctx = { price: p, position: s.position_usd / p, loss_today: s.loss_today, orders_today: s.orders_today };
      c.reasons = check({ symbol: o.symbol, side: o.side, qty: o.usd / p }, ctx, rules);
      c.decision = c.reasons.length ? 'block' : 'allow';
    });
    return cases;
  }

  root.mandateExamples = examples;
  if (typeof module !== 'undefined') module.exports = { examples: examples, check: check };
})(typeof window !== 'undefined' ? window : globalThis);
