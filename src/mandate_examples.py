"""Worked examples for a draft mandate: what the gate would do with a handful of concrete orders.

Writing limits is the easy half; knowing what they will do is the hard half. Before the owner signs,
``examples`` turns the scope into five to eight concrete orders placed right at its edges (one dollar
over the single-order limit, a symbol just off the list, a buy after the daily loss is hit, a sell that
cuts a losing position after it is hit) and runs each through the gate's own rule check
(``agent_gate.check``). The owner confirms the decisions, not the JSON.

The examples are generated by code from the scope, never by a language model, so a mistranslated
sentence shows up as a surprising decision here instead of hiding in a signed document. A language
model may draft the scope from the owner's words (the gate's MCP tool ``propose_mandate`` lets the
owner's own agent do that); it never decides what an example does.

    python src/mandate_examples.py --scope '{"allow":["AAPL","SPY"],"max_order_usd":500,...}'
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from typing import Any, Callable, Dict, List, Optional

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import agent_gate  # noqa: E402

OFF_LIST = ("TSLA", "NVDA", "DOGE", "BTC", "AAPL", "QQQ")
DEFAULT_PRICE = 100.0


def _r(x: float) -> float:
    return round(x, 2)


def examples(scope: Dict[str, Any], price_of: Optional[Callable[[str], float]] = None) -> List[Dict[str, Any]]:
    """Concrete orders at the scope's edges, each with the gate's decision and reasons.

    ``price_of(symbol)`` sizes the orders; any positive price works, because every rule is in dollars.
    Each example: title_zh, title_en, order {symbol, side, usd}, situation {position_usd, loss_today,
    orders_today}, decision ("allow" or "block"), reasons (the gate's own words).
    """
    price_of = price_of or (lambda s: DEFAULT_PRICE)
    allow = [s.upper() for s in scope.get("allow") or []]
    sides = scope.get("sides") or ["buy", "sell"]
    mo = scope.get("max_order_usd")
    mp = scope.get("max_position_usd")
    ml = scope.get("max_daily_loss_usd")
    mn = scope.get("max_orders_per_day")
    sym = allow[0] if allow else "AAPL"
    small = _r(min(mo * 0.6, 300.0) if mo else 300.0)
    open_side = "buy" if "buy" in sides else "sell"
    cases: List[Dict[str, Any]] = []

    def add(zh: str, en: str, symbol: str, side: str, usd: float, position_usd: float = 0.0,
            loss_today: float = 0.0, orders_today: int = 0) -> None:
        cases.append({"title_zh": zh, "title_en": en,
                      "order": {"symbol": symbol, "side": side, "usd": _r(usd)},
                      "situation": {"position_usd": _r(position_usd), "loss_today": _r(loss_today),
                                    "orders_today": orders_today}})

    add(f"平常的一笔：{'买' if open_side == 'buy' else '卖'} {sym} ${small:,.0f}",
        f"An ordinary order: {open_side} {sym} ${small:,.0f}", sym, open_side, small)
    if mo is not None:
        add(f"比单笔上限多 1 美元：{sym} ${mo + 1:,.0f}", f"One dollar over the single-order limit: {sym} ${mo + 1:,.0f}",
            sym, open_side, mo + 1)
    if allow:
        off = next(s for s in OFF_LIST + ("ZZZZ",) if s not in allow)
        add(f"不在名单上的标的：{off} ${small:,.0f}", f"A symbol not on the list: {off} ${small:,.0f}", off, open_side, small)
    if "sell" not in sides:
        add(f"手里没有 {sym} 时卖出（做空）", f"Selling {sym} with none held (going short)", sym, "sell", small)
    if mp is not None:
        held = max(mp - (mo or mp) / 2, 0.0)
        buy = (mo or mp) * 0.9
        add(f"已持有 {sym} ${held:,.0f}，再买 ${buy:,.0f}（超过单标的仓位上限 ${mp:,.0f}）",
            f"Holding ${held:,.0f} of {sym}, buying ${buy:,.0f} more (past the ${mp:,.0f} position limit)",
            sym, open_side, buy, position_usd=held if open_side == "buy" else -held)
    if ml is not None:
        add(f"今天已亏 ${ml:,.0f}，再开新仓 ${small:,.0f}", f"Down ${ml:,.0f} today, opening ${small:,.0f} more",
            sym, open_side, small, loss_today=ml)
        held = min(mp or 1000.0, 1000.0)
        cut = _r(held / 2)
        add(f"今天已亏 ${ml:,.0f}，卖出一半持仓止损 ${cut:,.0f}", f"Down ${ml:,.0f} today, selling half the position (${cut:,.0f}) to cut the loss",
            sym, "sell" if open_side == "buy" else "buy", cut,
            position_usd=held if open_side == "buy" else -held, loss_today=ml)
    if mn is not None:
        add(f"今天已下满 {mn} 笔，再下一笔", f"{mn} orders already today, one more", sym, open_side, small, orders_today=mn)

    rules = {k: scope.get(k) for k in agent_gate.mandate_mod.SCOPE_KEYS if k in scope}
    rules["allow"] = allow
    for c in cases:
        o, s = c["order"], c["situation"]
        p = float(price_of(o["symbol"])) or DEFAULT_PRICE
        ctx = {"price": p, "position": s["position_usd"] / p, "loss_today": s["loss_today"],
               "orders_today": s["orders_today"]}
        reasons = agent_gate.check({"symbol": o["symbol"], "side": o["side"], "qty": o["usd"] / p}, ctx, rules)
        c["decision"] = "block" if reasons else "allow"
        c["reasons"] = reasons
    return cases


def render(cases: List[Dict[str, Any]], lang: str = "zh") -> str:
    mark = {"allow": "放行" if lang == "zh" else "ALLOW", "block": "拦下" if lang == "zh" else "BLOCK"}
    out = []
    for i, c in enumerate(cases, 1):
        line = f"{i}. {c['title_' + lang]}  ->  {mark[c['decision']]}"
        if c["reasons"]:
            line += f"\n     {'; '.join(c['reasons'])}"
        out.append(line)
    return "\n".join(out)


def main(argv: Optional[List[str]] = None) -> None:
    ap = argparse.ArgumentParser(description="What a draft mandate would do with orders at its edges.")
    ap.add_argument("--scope", required=True, help="the scope as JSON, or a mandate / draft file")
    ap.add_argument("--lang", choices=["zh", "en"], default="zh")
    ap.add_argument("--json", action="store_true")
    a = ap.parse_args(argv)
    if os.path.exists(a.scope):
        with open(a.scope, encoding="utf-8") as f:
            doc = json.load(f)
        scope = (doc.get("mandate") or doc).get("scope", doc)
    else:
        scope = json.loads(a.scope)
    cases = examples(scope)
    print(json.dumps(cases, indent=1, ensure_ascii=False) if a.json else render(cases, a.lang))


if __name__ == "__main__":
    main()
